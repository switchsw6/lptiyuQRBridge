"""Local WeChat DiffDev QR bridge. OAuth codes go only to the requesting app.

Run with an ignored credentials JSON generated by build_qr_bridge.py.
No business login, account database edits, or synthetic OAuth results occur here.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import hmac
import json
from pathlib import Path
import re
import secrets
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import parse_qs, urlencode, urlsplit
from urllib.request import Request, urlopen

APP_ID = "wx5a2e1ff396785475"


def request_json(endpoint, params=None, body=None, timeout=40):
    url = endpoint + ("?" + urlencode(params) if params else "")
    request = Request(url, data=json.dumps(body).encode() if body is not None else None,
                      headers={"Content-Type": "application/json"})
    with urlopen(request, timeout=timeout) as response:
        return json.loads(response.read())


def qr_signature(ticket, nonce, timestamp):
    value = f"appid={APP_ID}&noncestr={nonce}&sdk_ticket={ticket}&timestamp={timestamp}"
    return hashlib.sha1(value.encode()).hexdigest()


def parse_poll(raw):
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        status = re.search(r"wx_errcode\s*=\s*(\d+)", raw)
        code = re.search(r"wx_code\s*=\s*['\"]([A-Za-z0-9_-]*)['\"]", raw)
        if status is None:
            raise ValueError("Unrecognized WeChat poll response")
        return {"wx_errcode": int(status.group(1)), "wx_code": code.group(1) if code else ""}


class Bridge:
    def __init__(self, config_path, state_dir):
        self.config = json.loads(Path(config_path).read_text(encoding="utf-8"))
        self.state_dir = Path(state_dir)
        self.state_dir.mkdir(parents=True, exist_ok=True)
        self.sessions = {}
        self.lock = threading.Lock()
        self.ticket_lock = threading.Lock()

    def record(self, event, **fields):
        # Deliberately omit codes, tickets, access tokens, and request URLs.
        entry = {"time": time.time(), "event": event, **fields}
        with self.lock:
            with (self.state_dir / "server-events.jsonl").open("a", encoding="utf-8") as stream:
                stream.write(json.dumps(entry, ensure_ascii=False) + "\n")
        print(json.dumps(entry, ensure_ascii=True), flush=True)

    def ticket(self):
        with self.ticket_lock:
            cache = self.state_dir / "sdk-ticket-response.private.json"
            if cache.exists():
                saved = json.loads(cache.read_text(encoding="utf-8"))
                if saved.get("ticket") and time.time() - cache.stat().st_mtime < saved.get("expires_in", 0) - 120:
                    return saved["ticket"]
            token = request_json("https://api.weixin.qq.com/cgi-bin/stable_token", body={
                "appid": APP_ID, "secret": self.config["app_secret"],
                "grant_type": "client_credential", "force_refresh": False})
            if not token.get("access_token"):
                raise RuntimeError(f"WeChat token error {token.get('errcode')}")
            ticket = request_json("https://api.weixin.qq.com/cgi-bin/ticket/getticket",
                                  {"access_token": token["access_token"], "type": 2})
            if ticket.get("errcode") != 0 or not ticket.get("ticket"):
                raise RuntimeError(f"WeChat SDK ticket error {ticket.get('errcode')}")
            cache.write_text(json.dumps(ticket), encoding="utf-8")
            return ticket["ticket"]

    def create(self, appid, scope):
        if appid != APP_ID or scope != "snsapi_userinfo":
            raise ValueError("Only the recovered Lepao app and scope are supported")
        nonce, stamp = secrets.token_hex(16), str(int(time.time()))
        result = request_json("https://open.weixin.qq.com/connect/sdk/qrconnect", {
            "appid": APP_ID, "noncestr": nonce, "timestamp": stamp,
            "scope": scope, "signature": qr_signature(self.ticket(), nonce, stamp)})
        if result.get("errcode") != 0 or not result.get("uuid"):
            raise RuntimeError(f"WeChat QR error {result.get('errcode')}")
        # Bind the shown name to the actual provider response.
        image = base64.b64decode(result["qrcode"]["qrcodebase64"], validate=True)
        sid = secrets.token_urlsafe(24)
        with self.lock:
            now = time.time()
            self.sessions = {k: v for k, v in self.sessions.items() if now - v["created"] < 300}
            self.sessions[sid] = {"uuid": result["uuid"], "created": now, "consumed": False}
        self.record("qr_created", appname=result.get("appname"), png_bytes=len(image))
        return {"id": sid, "appname": result.get("appname", ""),
                "png": base64.b64encode(image).decode()}

    def poll(self, sid):
        with self.lock:
            session = self.sessions.get(sid)
            if not session or session["consumed"] or time.time() - session["created"] > 300:
                return {"status": "expired"}
            uuid = session["uuid"]
        url = "https://long.open.weixin.qq.com/connect/l/qrconnect?" + urlencode({"f": "json", "uuid": uuid})
        with urlopen(url, timeout=45) as response:
            result = parse_poll(response.read().decode("utf-8"))
        number = int(result.get("wx_errcode", -1))
        state = {402: "expired", 403: "canceled", 404: "scanned", 405: "confirmed", 408: "waiting"}.get(number, "error")
        output = {"status": state, "provider_status": number}
        if number == 405:
            code = result.get("wx_code", "")
            if not re.fullmatch(r"[A-Za-z0-9_-]{6,256}", code):
                raise ValueError("Missing or invalid authorization code")
            with self.lock:
                if session["consumed"]:
                    return {"status": "expired"}
                session["consumed"] = True
            output["code"] = code
        self.record("poll", status=state, provider_status=number)
        return output


def handler_for(bridge):
    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *_):
            pass

        def answer(self, status, data):
            raw = json.dumps(data, ensure_ascii=False).encode()
            self.send_response(status)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Cache-Control", "no-store")
            self.send_header("Content-Length", str(len(raw)))
            self.end_headers()
            try:
                self.wfile.write(raw)
            except (BrokenPipeError, ConnectionResetError):
                pass

        def authorized(self):
            if not hmac.compare_digest(self.headers.get("X-Bridge-Token", ""), bridge.config["bridge_token"]):
                self.answer(403, {"error": "Bridge token required"})
                return False
            return True

        def do_GET(self):
            if not self.authorized():
                return
            parts = urlsplit(self.path)
            try:
                if parts.path == "/health":
                    return self.answer(200, {"status": "ready", "appid": APP_ID})
                if parts.path == "/poll":
                    return self.answer(200, bridge.poll(parse_qs(parts.query).get("id", [""])[0]))
                self.answer(404, {"error": "Unknown route"})
            except Exception as exc:
                bridge.record("request_failed", kind=type(exc).__name__)
                self.answer(502, {"error": type(exc).__name__})

        def do_POST(self):
            if not self.authorized():
                return
            try:
                length = int(self.headers.get("Content-Length", "0"))
                if self.path != "/session" or not 0 < length < 1024:
                    return self.answer(400, {"error": "Invalid request"})
                body = json.loads(self.rfile.read(length))
                self.answer(200, bridge.create(body.get("appid"), body.get("scope")))
            except ValueError:
                self.answer(400, {"error": "Invalid request"})
            except Exception as exc:
                bridge.record("request_failed", kind=type(exc).__name__)
                self.answer(502, {"error": type(exc).__name__})
    return Handler


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--credentials", required=True)
    parser.add_argument("--state-dir", required=True)
    parser.add_argument("--port", type=int, default=18371)
    args = parser.parse_args()
    bridge = Bridge(args.credentials, args.state_dir)
    server = ThreadingHTTPServer(("127.0.0.1", args.port), handler_for(bridge))
    bridge.record("listening", port=args.port)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
